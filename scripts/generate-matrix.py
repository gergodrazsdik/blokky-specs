"""Generate the validity-matrix cases of the conformance suite (CF-45).

Usage (from the repository root):
  uv run -q scripts/generate-matrix.py

Writes one validation case per cell of the validity matrix (reference.md §7)
and of the repetition sibling table (reference.md §5.2) into
conformance/cases/reference/matrix/: a minimal valid plan, run with testkit
leaves that exit 0, for each valid cell, and a plan error for each "—" cell.
Both tables are transcribed below as data; the Markdown isn't parsed, so a
change to either table needs a matching change here.

The output is deterministic. Before writing, the script removes the files it
generated earlier in that directory (recognized by MARKER in their notes) and
nothing else.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "conformance" / "cases" / "reference" / "matrix"
MARKER = "Generated by scripts/generate-matrix.py"
NOTES_MATRIX = f"{MARKER} from reference.md §7 (CF-45)."
NOTES_SIBLINGS = f"{MARKER} from reference.md §5.2 (CF-45)."

LEAF = "exec: [blokky-testkit, exit, '0']"
TRUE_COND = "{ path: ., is_dir: true }"
FALSE_COND = "{ path: missing.txt, exists: true }"
IMAGE = "docker.io/library/alpine:3.20"


# --- plan fragments -----------------------------------------------------------


@dataclass(frozen=True)
class Frag:
    """Keys of the node under test: YAML lines at node level, the first one holding the key."""

    lines: tuple[str, ...]
    features: frozenset[str] = frozenset()


def frag(*lines: str, features: tuple[str, ...] = ()) -> Frag:
    return Frag(tuple(lines), frozenset(features))


@dataclass(frozen=True)
class Kind:
    name: str
    base: Frag
    article: str = "a"
    shells: tuple[str, ...] = ()
    fails_with: str | None = None  # error code when the node runs (fail)


KINDS = {
    k.name: k
    for k in (
        Kind("exec", frag(LEAF, features=("exec",)), "an"),
        Kind(
            "script",
            frag("script: |", "  exit 0", "shell: sh", features=("script", "shell-sh")),
            shells=("sh",),
        ),
        Kind("do", frag("do:", f"  - {LEAF}", features=("do", "exec"))),
        Kind("all", frag("all:", f"  - {LEAF}", features=("all", "exec")), "an"),
        Kind("any", frag("any:", f"  - {LEAF}", features=("any", "exec")), "an"),
        Kind("race", frag("race:", f"  - {LEAF}", features=("race", "exec"))),
        Kind(
            "if", frag(f"if: {TRUE_COND}", "then:", f"  - {LEAF}", features=("if", "cond-path", "exec")), "an"
        ),
        Kind("assert", frag(f"assert: {TRUE_COND}", features=("assert", "cond-path")), "an"),
        Kind("log", frag("log: matrix", features=("log",))),
        Kind("sleep", frag("sleep: 0s", features=("sleep",))),
        Kind("fail", frag("fail: matrix", features=("fail",)), fails_with="BK_FAIL"),
        Kind("set", frag("set: { MATRIX_VALUE: '1' }", features=("set",))),
        Kind("return", frag("return: matrix", features=("return",))),
    )
}

FOR = frag("for: { each: [a], as: ITEM }", features=("for-each",))
RETRY = frag("retry: true", features=("retry",))
WHILE = frag(f"while: {FALSE_COND}", "max: 1", features=("while", "cond-path"))
UNTIL = frag(f"until: {TRUE_COND}", "max: 1", features=("until", "cond-path"))
REPETITION = {"retry": RETRY, "while": WHILE, "until": UNTIL, "for": FOR}


def modifier(key: str, stem: str) -> Frag:
    """The valid form of a modifier or companion field; `stem` names the case (lock names, CF-14)."""
    match key:
        case "name":
            return frag("name: matrix node")
        case "when":
            return frag(f"when: {TRUE_COND}", features=("when", "cond-path"))
        case "timeout":
            return frag("timeout: 1m", features=("timeout",))
        case "finally":
            return frag("finally:", f"  - {LEAF}", features=("finally", "exec"))
        case "ignore_errors":
            return frag("ignore_errors: true", features=("ignore-errors",))
        case "cwd":
            return frag("cwd: sub", features=("cwd",))
        case "env":
            return frag("env: { MATRIX_ENV: '1' }", features=("env",))
        case "export":
            return frag("export: [MATRIX_EXPORT]", features=("export",))
        case "tempdir":
            return frag("tempdir: { remove: true }", features=("tempdir",))
        case "lock":
            return frag(f"lock: conf-{stem}", features=("lock",))
        case "container":
            return frag(f"container: {{ image: {IMAGE} }}", features=("container",))
        case "services":
            return frag(
                "services:",
                "  - name: svc",
                "    exec: [blokky-testkit, print, --out, ready, --hang]",
                "    ready: { output: stdout, contains: ready }",
                features=("services",),
            )
        case "retry" | "while" | "until" | "for":
            return REPETITION[key]
        case "attempt_timeout":
            return frag("attempt_timeout: 1m", features=("attempt-timeout",))
        case "leaf_options":
            return frag("ok_exit: [1]", features=("ok-exit",))
        case "concurrency":
            return frag("concurrency: 1")
        case "fail_fast":
            return frag("fail_fast: false")
        case "then":
            return frag("then:", f"  - {LEAF}", features=("exec",))
        case "else":
            return frag("else:", f"  - {LEAF}", features=("exec",))
        case "shell":
            return frag("shell: sh", features=("shell-sh",))
        case "level":
            return frag("level: warn")
        case "message":
            return frag("message: matrix")
        case "code":
            return frag("code: MATRIX_CODE")
    raise KeyError(key)


# --- the tables -----------------------------------------------------------------

# reference.md §7, the validity matrix. Y = valid, N = plan error ("—"),
# REP = valid only with a repetition modifier, FOR = valid only inside `for:`.
Y, N, REP, FOR_ONLY = "Y", "N", "REP", "FOR"
SCOPE = ("cwd", "env", "export", "tempdir", "lock", "container", "services")
COLUMNS = ("scope", "repeat", "for", "attempt_timeout", "leaf_options", "concurrency", "fail_fast")
MATRIX = {
    #          scope retry/while/until for attempt_timeout leaf  concurrency fail_fast
    "exec": (Y, Y, Y, REP, Y, FOR_ONLY, FOR_ONLY),
    "script": (Y, Y, Y, REP, Y, FOR_ONLY, FOR_ONLY),
    "do": (Y, Y, Y, REP, N, FOR_ONLY, Y),
    "all": (Y, Y, Y, REP, N, Y, Y),
    "any": (Y, Y, Y, REP, N, Y, FOR_ONLY),
    "race": (Y, Y, Y, REP, N, FOR_ONLY, FOR_ONLY),
    "if": (Y, Y, Y, REP, N, FOR_ONLY, FOR_ONLY),
    "assert": (Y, Y, Y, REP, N, FOR_ONLY, FOR_ONLY),
    "log": (N, N, Y, N, N, FOR_ONLY, FOR_ONLY),
    "sleep": (N, N, N, N, N, N, N),
    "fail": (N, N, N, N, N, N, N),
    "set": (N, N, N, N, N, N, N),
    "return": (N, N, N, N, N, N, N),
}
# reference.md §7, the paragraph above the table: `name` and `when` are valid
# on every kind; `timeout`, `finally` and `ignore_errors` on every kind but these.
NO_PROCESS = ("sleep", "log", "fail", "set", "return")
# reference.md §7, the paragraph under the table: companion fields and their owners (RF-32).
COMPANIONS = {
    "then": ("if",),
    "else": ("if",),
    "shell": ("script",),
    "level": ("log",),
    "message": ("assert",),
    "code": ("fail", "assert"),
}

# reference.md §5.2, the sibling table: field -> modifiers it is valid with.
SIBLINGS = {
    "max": ("retry", "while", "until"),
    "every": ("retry", "while", "until"),
    "attempt_timeout": ("retry", "while", "until", "for"),
    "backoff": ("retry",),
    "jitter": ("retry",),
    "on_body_failure": ("while", "until"),
    "index": ("retry", "while", "until"),
    "carry": ("while", "until"),
    "collect": ("for", "while", "until"),
}
SIBLING_FORMS = {
    "every": frag("every: 0s"),
    "attempt_timeout": frag("attempt_timeout: 1m", features=("attempt-timeout",)),
    "backoff": frag("backoff: { factor: 2 }", features=("backoff",)),
    "jitter": frag("jitter: 0.5", features=("jitter",)),
    "on_body_failure": frag("on_body_failure: stop"),
    "index": frag("index: ATTEMPT", features=("index",)),
    "carry": frag("carry: { PREV: OUT }", features=("carry",)),
    "collect": frag("collect: { OUT: OUTS }", features=("collect",)),
}
CAPTURE = frag("capture: OUT", features=("capture",))
FINALLY_TIMEOUT = frag("finally_timeout: 1m")
# The rule a "—" sibling cell breaks, where §8 names one more specific than RF-3.
SIBLING_RULES = {"attempt_timeout": "RF-4", "index": "RF-30", "carry": "RF-30", "collect": "RF-30"}

# Valid cells that get no case, with the reason (reported, not silently dropped).
SKIPPED: list[str] = []


# --- case assembly ------------------------------------------------------------------


@dataclass
class Case:
    stem: str
    title: str
    rules: list[str]
    section: str
    kind: Kind
    frags: list[Frag]
    error: tuple[str, int] | None = None  # (rule, index of the offending fragment)
    extra_features: set[str] = field(default_factory=set)

    def render(self) -> str:
        frags = [self.kind.base, *self.frags]
        root = ["blokky: 1.0"]
        features = {"do", *self.extra_features}
        if any(f.lines[0].startswith("export:") for f in frags):
            root += ["vars:", "  MATRIX_EXPORT: '1'"]
            features.add("vars")
        root.append("do:")
        node: list[str] = []
        error_line = 0
        for i, f in enumerate(frags):
            if self.error and i == self.error[1] + 1:
                error_line = len(root) + len(node) + 1
            node += f.lines
            features |= f.features
        plan = root + [("  - " if i == 0 else "    ") + line for i, line in enumerate(node)]

        out = [f"title: {self.title}", f"rules: [{', '.join(self.rules)}]", f"spec: [{self.section}]"]
        out.append(f"features: [{', '.join(sorted(features))}]")
        if self.kind.shells and not self.error:  # a plan error runs no shell
            out.append(f"requires: {{ shells: [{', '.join(self.kind.shells)}] }}")
            out.append("clock: [real]")  # script leaves (CF-40)
        if any(f.lines[0] == "cwd: sub" for f in frags):
            out += ["files:", "  sub: { dir: true }"]
        out.append("plan: |")
        out += [f"  {line}" for line in plan]
        out.append("expect:")
        if self.error:
            out += [
                "  plan_errors:",
                "    - code: BK_PLAN_INVALID",
                f"      detail: {{ rule: {self.error[0]} }}",
                f"      line: {error_line}",
                "      column: 5",
            ]
        elif self.kind.fails_with:
            code = "MATRIX_CODE" if any(f.lines[0] == "code: MATRIX_CODE" for f in frags) else "BK_FAIL"
            out += [
                "  status: failed",
                f"  error: {{ code: {code}, node: /do/0 }}",
                "  nodes:",
                "    /do/0: { status: failed }",
            ]
        else:
            out += ["  status: succeeded", "  error: null", "  nodes:", "    /do/0: { status: succeeded }"]
        notes = NOTES_SIBLINGS if self.section == "reference.md§5.2" else NOTES_MATRIX
        out.append(f"notes: {notes}")
        return "\n".join(out) + "\n"


def label(key: str) -> str:
    return key.replace("_", "-")


def on(kind: Kind) -> str:
    return f"on {kind.article} {kind.name} node"


def valid(stem: str, title: str, rule: str, kind: Kind, frags: list[Frag]) -> Case:
    return Case(stem, f"{title} is valid", [rule], "reference.md§7", kind, frags)


def invalid(stem: str, title: str, rule: str, kind: Kind, frags: list[Frag], offending: int) -> Case:
    return Case(stem, f"{title} is a plan error", [rule], "reference.md§7", kind, frags, (rule, offending))


def matrix_cases() -> list[Case]:
    cases: list[Case] = []
    for name, kind in KINDS.items():
        cells = dict(zip(COLUMNS, MATRIX[name], strict=True))

        def single(key: str, ok: bool, rule: str, kind: Kind = kind) -> None:
            stem = f"{kind.name}-{label(key)}"
            text = f"{key} {on(kind)}"
            frags = [modifier(key, stem)]
            cases.append(
                valid(stem, text, rule, kind, frags) if ok else invalid(stem, text, rule, kind, frags, 0)
            )

        for key in ("name", "when"):
            single(key, True, "RF-3")
        for key in ("timeout", "finally", "ignore_errors"):
            single(key, name not in NO_PROCESS, "RF-28")
        if name in NO_PROCESS:
            # With `finally` too, so the only rule broken by finally_timeout is RF-28, not RF-32
            # (the `finally` key breaks RF-28 as well; that error isn't asserted).
            text = f"finally_timeout {on(kind)}"
            frags = [modifier("finally", ""), FINALLY_TIMEOUT]
            cases.append(invalid(f"{name}-finally-timeout", text, "RF-28", kind, frags, 1))
        for key in SCOPE:
            if key == "container" and cells["scope"] == Y:
                SKIPPED.append(f"{name}-container")
                continue
            single(key, cells["scope"] == Y, "RF-3")
        for key in ("retry", "while", "until"):
            single(key, cells["repeat"] == Y, "RF-3")
        single("for", cells["for"] == Y, "RF-3")
        single("leaf_options", cells["leaf_options"] == Y, "RF-3")

        # attempt_timeout: "with repetition" (RF-4), or "—".
        at = modifier("attempt_timeout", "")
        if cells["attempt_timeout"] == REP:
            stem = f"{name}-attempt-timeout"
            cases.append(valid(stem, f"attempt_timeout with retry {on(kind)}", "RF-4", kind, [RETRY, at]))
            text = f"attempt_timeout without repetition {on(kind)}"
            cases.append(invalid(f"{stem}-without-repetition", text, "RF-4", kind, [at], 0))
        elif cells["for"] == Y:
            # log: `for` is valid but attempt_timeout isn't, which the schema doesn't enforce,
            # so only the cell without repetition gets a case.
            SKIPPED.append(f"{name}-attempt-timeout (with for)")
            text = f"attempt_timeout without repetition {on(kind)}"
            cases.append(invalid(f"{name}-attempt-timeout-without-repetition", text, "RF-4", kind, [at], 0))
        else:
            # No repetition is valid on the kind, so RF-4 applies as well as RF-3.
            cases.append(
                invalid(f"{name}-attempt-timeout", f"attempt_timeout {on(kind)}", "RF-4", kind, [at], 0)
            )

        # concurrency and fail_fast: valid, "for only" or "—"; RF-31 beside `for`.
        for key in ("concurrency", "fail_fast"):
            stem, cell = f"{name}-{label(key)}", cells[key]
            node_level = modifier(key, stem)
            if cell == Y:
                cases.append(valid(stem, f"node-level {key} {on(kind)}", "RF-3", kind, [node_level]))
                text = f"node-level {key} beside for {on(kind)}"
                cases.append(invalid(f"{stem}-beside-for", text, "RF-31", kind, [FOR, node_level], 1))
            elif cell == FOR_ONLY:
                value = "concurrency: 2" if key == "concurrency" else "fail_fast: false"
                in_for = frag(
                    f"for: {{ each: [a], as: ITEM, {value} }}",
                    features=("for-each", "for-concurrency") if key == "concurrency" else ("for-each",),
                )
                cases.append(valid(f"{stem}-in-for", f"{key} inside for {on(kind)}", "RF-3", kind, [in_for]))
                text = f"node-level {key} {on(kind)}"
                cases.append(invalid(stem, text, "RF-3", kind, [node_level], 0))
            else:
                cases.append(invalid(stem, f"{key} {on(kind)}", "RF-3", kind, [node_level], 0))

        # Companion fields only on their kind (RF-32).
        for key, owners in COMPANIONS.items():
            if name in owners and key in ("then", "shell"):
                continue  # part of the kind's base plan
            stem = f"{name}-companion-{label(key)}"
            text = f"companion {key} {on(kind)}"
            frags = [modifier(key, stem)]
            if name in owners:
                cases.append(valid(stem, text, "RF-32", kind, frags))
            else:
                cases.append(invalid(stem, text, "RF-32", kind, frags, 0))
    # finally_timeout without finally (RF-32): one kind suffices, the rule doesn't depend on it.
    text = "finally_timeout without finally on an exec node"
    cases.append(
        invalid("exec-finally-timeout-without-finally", text, "RF-32", KINDS["exec"], [FINALLY_TIMEOUT], 0)
    )
    return cases


def sibling_cases() -> list[Case]:
    kind = KINDS["exec"]
    cases: list[Case] = []
    for key, valid_with in SIBLINGS.items():
        for mod, rep in REPETITION.items():
            stem = f"siblings-{label(key)}-{mod}"
            frags = [rep]
            if key in ("carry", "collect"):
                frags.append(CAPTURE)  # the capture they name (RF-30)
            ok = mod in valid_with
            if key == "max":
                form = frag("max: 2")
                if mod in ("while", "until"):
                    form = None  # the loop's base form already has max (RF-5)
            else:
                form = SIBLING_FORMS[key]
            if form is not None:
                frags.append(form)
            title = f"{key} with {mod} on an exec node is " + ("valid" if ok else "a plan error")
            rule = SIBLING_RULES.get(key, "RF-3")
            error = None if ok else (rule, len(frags) - 1)
            cases.append(Case(stem, title, [rule], "reference.md§5.2", kind, frags, error))
    return cases


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for path in sorted(OUT.glob("*.yaml")):
        if MARKER in path.read_text(encoding="utf-8"):
            path.unlink()
    cases = matrix_cases() + sibling_cases()
    stems = [c.stem for c in cases]
    assert len(stems) == len(set(stems)), "duplicate case file names"
    for case in cases:
        (OUT / f"{case.stem}.yaml").write_text(case.render(), encoding="utf-8", newline="\n")
    errors = sum(1 for c in cases if c.error)
    print(f"{len(cases)} cases in {OUT.relative_to(ROOT)}: {len(cases) - errors} valid, {errors} plan errors")
    if SKIPPED:
        print(f"skipped valid cells: {', '.join(SKIPPED)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
